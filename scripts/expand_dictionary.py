def expand_dictionary():
    dict_path = os.path.join(PROJECT_ROOT, "data", "dictionaries", "lao_vi_en.csv")
    print(f"[*] Đang nạp từ điển hiện tại: {dict_path}")
    
    existing_entries = {}
    if os.path.exists(dict_path):
        with open(dict_path, mode="r", encoding="utf-8-sig") as f:
            reader = csv.DictReader(f)
            for row in reader:
                norm_lao = normalize_lao(row.get("lao", "").strip())
                if norm_lao:
                    existing_entries[norm_lao] = {
                        "lao": norm_lao,
                        "vi": row.get("vi", "").strip(),
                        "en": row.get("en", "").strip(),
                        "romanization": row.get("romanization", "").strip(),
                        "pos": row.get("pos", "").strip(),
                        "lesson": row.get("lesson", "").strip(),
                        "example_lao": normalize_lao(row.get("example_lao", "").strip()),
                        "example_vi": row.get("example_vi", "").strip(),
                    }
    
    old_count = len(existing_entries)
    print(f"[*] Số lượng từ điển gốc: {old_count} mục từ.")
    
    # Bổ sung danh sách mở rộng
    added_count = 0
    for item in EXPANSION_VOCAB:
        lao_word, vi, en, rom, pos, cat, ex_lao, ex_vi = item
        norm_lao = normalize_lao(lao_word.strip())
        if not norm_lao:
            continue
        
        # Nếu chưa có thì bổ sung
        if norm_lao not in existing_entries:
            existing_entries[norm_lao] = {
                "lao": norm_lao,
                "vi": vi.strip(),
                "en": en.strip(),
                "romanization": rom.strip(),
                "pos": pos.strip(),
                "lesson": f"Mở rộng - {cat.strip()}",
                "example_lao": normalize_lao(ex_lao.strip()),
                "example_vi": ex_vi.strip(),
            }
            added_count += 1
            
    # Sắp xếp theo thứ tự bảng chữ cái tiếng Lào chuẩn NFC
    sorted_words = sorted(existing_entries.keys())
    
    # Ghi lại tệp CSV
    with open(dict_path, mode="w", encoding="utf-8", newline="") as f:
        fieldnames = ["lao", "vi", "en", "romanization", "pos", "lesson", "example_lao", "example_vi"]
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for w in sorted_words:
            writer.writerow(existing_entries[w])
            
    print(f"[+] Hoàn tất mở rộng từ điển!")
    print(f"    - Số mục từ ban đầu: {old_count}")
    print(f"    - Số mục từ mới nạp: {added_count}")
    print(f"    - Tổng mục từ hiện tại: {len(sorted_words)}")


if __name__ == "__main__":
    expand_dictionary()
